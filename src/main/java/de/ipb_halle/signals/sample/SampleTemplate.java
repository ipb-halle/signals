package de.ipb_halle.signals.sample;

public class SampleTemplate {
    private String templateId;
    private String templateName;

    public SampleTemplate() {
    }

    public SampleTemplate(SampleTemplateEntity ste) {
        this.templateId = ste.getTemplateId();
        this.templateName = ste.getTemplateName();
    }

    public SampleTemplateEntity createEntity() {
        return new SampleTemplateEntity()
                .setTemplateId(templateId)
                .setTemplateName(templateName);
    }

    //getter and setter

    public String getTemplateId() {
        return templateId;
    }

    public void setTemplateId(String templateId) {
        this.templateId = templateId;
    }

    public String getTemplateName() {
        return templateName;
    }

    public void setTemplateName(String templateName) {
        this.templateName = templateName;
    }
}
